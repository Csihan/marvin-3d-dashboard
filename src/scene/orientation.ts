/**
 * @file    orientation.ts
 * @brief   机器人朝向与左右手性的单一事实源（2026-09-04 方案 B 改造）
 * @author Csihan
 * @date    2026-09-04
 *
 * ─────────────────────────────────────────────────────────────────────────
 * 坐标约定（2026-09-04 定案，本文件是代码侧唯一实现）：
 *
 *   1. ROS/URDF 侧（URDF 根坐标系 base_footprint）：
 *        网格真实正面朝 URDF 的 -X（头/双臂挂载在 -0.48~-0.49 一侧,
 *        见 MODEL_YAW 注释的三重证据）；front_* 轮的"+0.35"是命名,
 *        不作为朝向依据。Y+ = 机器人左侧；Z+ = 向上。右手系。
 *   2. Web 场景侧（three.js，Y-up）：
 *        URDF 是 Z-up,加载后 rotation.x = -π/2（Z→Y）；
 *        再对模型容器施加 MODEL_YAW=π 的绕 Y 摆放旋转,把网格正面
 *        转到世界 +X——相机 home 机位在 +X 侧 → 打开页面即"面对面"。
 *        ⚠ 只允许纯旋转（det=+1）,禁止任何负缩放镜像（det=-1 会把
 *        关节转向全部视觉反转,即历史上"模型与真机反向"的根源）。
 *   3. 左右手性（2026-09-05 实测修正,纯旋转下自然成立）：
 *        相机在正面（+X）回望时,机器人自身 Y+（左）呈现在画面左侧,
 *        即"画面左 = 机器人左臂、画面右 = 机器人右臂"。
 *        ⚠ 旧版（2026-09-04）按"镜子镜像"写成 画面左=右臂,与 3D 投影
 *        实测相反（arm_l→屏幕左/arm_r→屏幕右）——面对面看对方时
 *        左右不互换。UI 若需按屏幕方位命名,引用 SCREEN_LEFT_IS。
 * ─────────────────────────────────────────────────────────────────────────
 */
import * as THREE from 'three'

/**
 * 模型摆放旋转（绕 Y,弧度）：把 URDF 网格的正面转到世界 +X。
 * 必须保持 Math.PI，使得升降导轨/拖链位于机器人后方，头和摄像头正对观察者。
 */
export const MODEL_YAW = Math.PI

/**
 * 机器人正面在世界坐标的单位方向向量。
 */
export const ROBOT_FRONT = new THREE.Vector3(1, 0, 0)

/**
 * 相机 home 机位方向：站在机器人正面（X+ 侧）回望原点。
 */
export const CAMERA_HOME_SIDE = ROBOT_FRONT.clone()

/**
 * 面对面视角下的左右映射（2026-09-05 定案：URDF 左右挂载 y 坐标修正后）：
 * - 画面左 = 机器人左臂（ARM_L / 左爪）
 * - 画面右 = 机器人右臂（ARM_R / 右爪）
 * 键 = 机器人臂侧（L/R），值 = 画面方位（robot_L = 画面左 / robot_R = 画面右）。
 * ⚠ 旧版（2026-09-04~09-05 早）按"镜子镜像"写成 L→robot_R（画面左=右臂），与
 *   URDF 挂载修正后的 3D 投影（arm_l→画面左）相反，已于定案时修正。
 */
export const SCREEN_LEFT_IS: Record<'L' | 'R', 'robot_R' | 'robot_L'> = {
  L: 'robot_L',
  R: 'robot_R',
}
